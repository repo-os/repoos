#!/usr/bin/env bun
/**
 * Extracts :root / [data-ui-theme] CSS custom-property blocks from the main
 * web UI stylesheet into mobile/src/design-tokens/ui-themes.css so the Hub
 * shell shares the same color themes (light + dark) without duplicating values
 * by hand.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join, dirname } from "node:path";

const mobileRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(mobileRoot, "..");
const stylePath = join(repoRoot, "src/ui-app/src/style.css");
const outPath = join(mobileRoot, "src/design-tokens/ui-themes.css");

const SHELL_VARS = new Set([
  "--bg",
  "--bg-2",
  "--panel",
  "--panel-solid",
  "--border",
  "--border-bright",
  "--txt",
  "--txt-dim",
  "--txt-faint",
  "--cyan",
  "--cyan-dim",
  "--violet",
  "--violet-dim",
  "--green",
  "--red",
  "--amber",
  "--body-gradient",
  "--logo-shadow",
  "--card-glow",
  "--overlay-bg",
  "--panel-gradient",
  "--btn-primary-bg",
  "--btn-primary-color",
  "--green-tint",
  "--green-border-tint",
  "--red-tint",
  "--red-border-tint",
  "--amber-tint",
  "--amber-border-tint",
  "--background",
  "--foreground",
  "--primary",
  "--primary-foreground",
  "--destructive",
  "--destructive-foreground",
  "--accent",
  "--accent-foreground",
  "--muted",
  "--muted-foreground",
  "--ring",
  "--color-scheme",
]);

const src = readFileSync(stylePath, "utf8");

/** @type {Array<{ selector: string; vars: string[] }>} */
const blocks = [];

const blockRe =
  /(:root(?:\[[^\]]+\])*(?:\[[^\]]+\])?|\[data-theme="light"\](?:\[[^\]]+\])?)\s*\{([^}]*)\}/g;

let m;
while ((m = blockRe.exec(src)) !== null) {
  const selector = m[1].trim();
  const body = m[2];
  if (!selector.startsWith(":root") && selector !== '[data-theme="light"]') continue;
  if (selector.includes("[data-ui-theme=") === false && selector !== ":root" && selector !== '[data-theme="light"]') {
    // keep :root[data-ui-theme=…] and plain [data-theme=light] variants
  }
  if (
    selector === ":root" ||
    selector.includes("[data-ui-theme=") ||
    selector === '[data-theme="light"]' ||
    selector.startsWith(':root[data-ui-theme=') ||
    selector.startsWith('[data-theme="light"][data-ui-theme=')
  ) {
    const vars = [];
    const varRe = /(--[a-z0-9-]+)\s*:\s*([^;]+);/g;
    let vm;
    while ((vm = varRe.exec(body)) !== null) {
      if (!SHELL_VARS.has(vm[1])) continue;
      const val = vm[2].trim();
      if (!val) continue;
      vars.push(`${vm[1]}: ${val};`);
    }
    if (vars.length > 0) blocks.push({ selector, vars });
  }
}

const header = `/* AUTO-GENERATED by mobile/scripts/sync-ui-theme-vars.mjs — do not edit by hand. */
/* Source: src/ui-app/src/style.css — shell token subset only. */\n\n`;

const body = blocks
  .map((b) => `${b.selector} {\n  ${b.vars.join("\n  ")}\n}`)
  .join("\n\n");

writeFileSync(outPath, header + body + "\n");
console.log(`Wrote ${blocks.length} theme blocks → ${outPath}`);
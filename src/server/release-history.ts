/**
 * Committed release history — the one record every public surface reads.
 *
 * A release used to leave only a git tag and a GitHub Release: the docs site,
 * the landing page and the generated llms files each guessed at the current
 * version (or fetched GitHub at build time), so they lagged behind a cut
 * (v0.5.75 QA). This module writes a release entry at cut time, before the
 * gate and before any ref is pushed, so the next docs/landing build already
 * contains the new version and date.
 *
 * `release-history.json` is the structured source of truth; `CHANGELOG.md` is
 * its human/GitHub-readable rendering. Both are committed with the version
 * bump, so the tag that CI releases already contains them.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export interface ReleaseHistoryEntry {
  /** Semantic version without the tag prefix, e.g. "0.5.76". */
  version: string;
  /** Full git tag, e.g. "v0.5.76". */
  tag: string;
  /** UTC release date, YYYY-MM-DD. */
  date: string;
  /** Markdown release notes, without a version heading. */
  notes: string;
  /**
   * Markdown known issues for the release email (#1071). Typed by the
   * operator in the release modal, never invented. Absent or empty means
   * "None recorded" in the email.
   */
  knownIssues?: string;
}

export interface ReleaseHistory {
  /** Newest first. */
  releases: ReleaseHistoryEntry[];
}

export const RELEASE_HISTORY_FILE = "release-history.json";
export const CHANGELOG_FILE = "CHANGELOG.md";

/** UTC date an entry is stamped with (`YYYY-MM-DD`). */
export function releaseDate(now: Date = new Date()): string {
  return now.toISOString().slice(0, 10);
}

export function emptyReleaseHistory(): ReleaseHistory {
  return { releases: [] };
}

/**
 * Read the committed history. A malformed file throws: silently returning an
 * empty history would let a release overwrite every earlier entry. A missing
 * file is a fresh repository and starts empty.
 */
export function readReleaseHistory(root: string): ReleaseHistory {
  const path = join(root, RELEASE_HISTORY_FILE);
  if (!existsSync(path)) return emptyReleaseHistory();
  let parsed: unknown;
  try {
    parsed = JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    throw new Error(
      `Could not parse ${RELEASE_HISTORY_FILE}: ${error instanceof Error ? error.message : String(error)}`,
    );
  }
  if (
    !parsed ||
    typeof parsed !== "object" ||
    !Array.isArray((parsed as ReleaseHistory).releases)
  ) {
    throw new Error(`${RELEASE_HISTORY_FILE} must be an object with a "releases" array.`);
  }
  const releases: ReleaseHistoryEntry[] = [];
  for (const raw of (parsed as ReleaseHistory).releases) {
    if (!raw || typeof raw !== "object") continue;
    const entry = raw as Partial<ReleaseHistoryEntry>;
    if (
      typeof entry.version !== "string" ||
      typeof entry.tag !== "string" ||
      typeof entry.date !== "string" ||
      typeof entry.notes !== "string"
    ) {
      throw new Error(
        `${RELEASE_HISTORY_FILE} has a malformed release entry: every entry needs version, tag, date and notes strings.`,
      );
    }
    releases.push({
      version: entry.version,
      tag: entry.tag,
      date: entry.date,
      notes: entry.notes,
      ...(typeof entry.knownIssues === "string" && entry.knownIssues.trim()
        ? { knownIssues: entry.knownIssues }
        : {}),
    });
  }
  return { releases };
}

/**
 * Insert or replace one release. Matching is by tag and then version, so a
 * retried cut (which skips the version-bump commit) refreshes its own entry
 * instead of duplicating it. New entries go first: the file is newest-first.
 */
export function upsertRelease(history: ReleaseHistory, entry: ReleaseHistoryEntry): ReleaseHistory {
  const releases = history.releases.filter(
    (existing) => existing.tag !== entry.tag && existing.version !== entry.version,
  );
  return { releases: [entry, ...releases] };
}

/** The default body when a cut supplied no notes: the release's commit subjects. */
export function renderDefaultReleaseNotes(commits: readonly string[]): string {
  const subjects = commits
    .map((commit) => commit.replace(/^[0-9a-f]{7,40}\s+/i, "").trim())
    .filter((subject) => subject !== "");
  if (subjects.length === 0) return "Maintenance release.";
  return ["Changes in this release:", "", ...subjects.map((subject) => `- ${subject}`)].join("\n");
}

/** Render `CHANGELOG.md` from the committed history. */
export function renderChangelog(history: ReleaseHistory): string {
  const parts = [
    "# Changelog",
    "",
    "Every RepoOS release, newest first. This file is generated by the release",
    "pipeline from `release-history.json`; the newest entry is also the GitHub",
    "release body. The full discussion of each change lives in the release notes",
    "and on GitHub.",
    "",
  ];
  for (const release of history.releases) {
    parts.push(
      `## [${release.tag}] - ${release.date}`,
      "",
      release.notes.trim(),
      "",
      `[Release on GitHub](https://github.com/repo-os/repoos/releases/tag/${release.tag})`,
      "",
    );
  }
  return `${parts.join("\n").trim()}\n`;
}

export interface ReleaseSurfaceWrite {
  /** Repo-relative paths written (or confirmed unchanged). */
  paths: string[];
  /** True when at least one file's contents changed on disk. */
  changed: boolean;
}

/**
 * Write both committed release surfaces for `entry`. Idempotent: a retry that
 * already wrote the entry reports `changed: false` and leaves the tree clean.
 */
export function writeReleaseSurfaces(
  root: string,
  entry: ReleaseHistoryEntry,
): ReleaseSurfaceWrite {
  const history = upsertRelease(readReleaseHistory(root), entry);
  const historyPath = join(root, RELEASE_HISTORY_FILE);
  const changelogPath = join(root, CHANGELOG_FILE);
  const nextHistory = `${JSON.stringify(history, null, 2)}\n`;
  const nextChangelog = renderChangelog(history);
  const previousHistory = existsSync(historyPath) ? readFileSync(historyPath, "utf8") : null;
  const previousChangelog = existsSync(changelogPath) ? readFileSync(changelogPath, "utf8") : null;
  let changed = false;
  if (previousHistory !== nextHistory) {
    writeFileSync(historyPath, nextHistory, "utf8");
    changed = true;
  }
  if (previousChangelog !== nextChangelog) {
    writeFileSync(changelogPath, nextChangelog, "utf8");
    changed = true;
  }
  return { paths: [RELEASE_HISTORY_FILE, CHANGELOG_FILE], changed };
}
